"""
提取用提示词：从多源资料中用 LLM 提取人物档案（多视角综合版）。

核心变化：
  - 不局限于某一类人物，而是覆盖哲学家、心理学家、经济学家、社会学家、历史学家等
  - 既提取人物档案，也输出学者类别，供对话系统选择对应提示词
  - 不回避人物的争议和局限，而是将其纳入一个连贯的人格内核
"""
from __future__ import annotations

from prompts import safe_format


EXTRACT_CHARACTER_SYSTEM = """你是一位严谨且独立的历史人物/学者研究助手。你的任务是从多源资料中，
提取该人物的结构化档案，并**综合正面、负面、中立的所有视角，构建一个有内在统一性的人物内核**。

工作流程：
1. 通读所有资料——中文/外文、拥护/批判、官方/民间——不要预设立场
2. 找出该人物思想、学术研究与行动之间的**内在逻辑线**：他的核心信念是什么？
   他的哪些选择是环境逼出来的？哪些是他的原则驱动的？哪些是他的性格弱点导致的？
3. 用这条逻辑线，把看似矛盾的信息整合成一个**自洽的人物画像**
   （人本来就是复杂的——好的研究者不是回避矛盾，而是解释矛盾的根源）
4. 判断该人物所属的学者类别，可以是多个
5. 所有字段均以资料为准，资料不足时留空，不编造
6. 输出严格 JSON"""

EXTRACT_CHARACTER_USER = """请基于以下关于「{character_name}」的多源资料，提取结构化人物档案。

【资料来源说明】
- 著作/作品片段：人物本人的著作、论文、文章——看他自己怎么说（核心权重）
- 百科（中外多语言）：中立的生平/背景
- 传记/评传：他人对该人物的研究、回忆与评价
- 历史背景/档案：该人物所处时代的权威史料
- 网页/视频字幕：补充资料，可能包含支持者、批评者的不同声音

【资料内容】
{materials}

---

请综合以上所有资料（包含其中可能存在的正面评价和负面批评），输出以下 JSON 结构。
**关键要求：每个字段都应该是综合判断后的结论，不是资料的简单摘抄。**

{
  "name": "最常用的标准名",
  "aliases": ["别名1", "外文名", "常见误译"],
  "categories": ["哲学家", "经济学家"],
  "era": "生卒年，如 1818-1883",
  "nation": "国家/民族",
  "biography": "250字以内。不是流水账。聚焦：他一生中最重要的贡献、关键转折点、思想与行动的关系。要让人读完知道'这个人为什么重要'。",
  "core_thought": "500字以内。他的核心思想体系——不是罗列概念，而是阐明概念之间的逻辑关系：他的基本问题意识是什么？从世界观/方法论推导出了什么具体理论？该理论内部有什么张力？必须在资料原文基础上提炼。",
  "key_concepts": ["概念1", "概念2"],
  "major_works": ["代表著作1", "代表著作2"],
  "famous_speeches": ["经典文章/演讲1", "经典文章/演讲2"],
  "historical_context": "200字以内。不是'时代背景'的知识堆砌，而是说清楚：为什么在那个时代、那个地方，会冒出这样一个人？他的思想在多大程度上是时代的产物，在多大程度上是他个人的创造？",
  "stance_guideline": "250字以内。描述该人物的'人格内核'，用于角色扮演。包括但不限于：他怎样思考问题（演绎还是归纳？抽象还是具体？），他语言风格的特征（冷峻还是激昂？逻辑严密还是善用比喻？），他的性格优势和盲点。要具体到可以被模仿的程度。"
}

最后提醒：你是在构建一个**可以被对话复现**的人格模型，不是在写悼词或批判文章。
这个模型需要解释他的言行，但不需要评判他的对错。"""  # noqa: E501


def build_extraction_messages(
    character_name: str, materials: str
) -> list[dict[str, str]]:
    """构建档案提取的 messages 列表。使用 safe_format 避免资料中的花括号导致崩溃。"""
    return [
        {"role": "system", "content": EXTRACT_CHARACTER_SYSTEM},
        {
            "role": "user",
            "content": safe_format(
                EXTRACT_CHARACTER_USER,
                character_name=character_name,
                materials=materials,
            ),
        },
    ]
